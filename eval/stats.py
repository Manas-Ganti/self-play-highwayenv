"""Statistics. CLAUDE.md §7 makes these rules non-negotiable, so they live in one
place and every reported number goes through them.

* Aggregate claims across seeds: IQM + stratified bootstrap 95% CI (rliable when
  installed; an equivalent local implementation otherwise, so the stats rules do
  not silently lapse just because a dependency is missing).
* Win rates: **paired**-episode permutation tests. Head-to-head episodes are run
  in pairs -- same traffic seed, starting positions swapped -- so the pairing must
  be preserved in the test. An unpaired test would throw away exactly the variance
  reduction the paired design bought.
* Never a single-seed curve as a finding; never a comparison at unequal budgets.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np


@dataclass
class Interval:
    """A point estimate with a confidence interval."""

    point: float
    low: float
    high: float

    def __str__(self) -> str:
        return f"{self.point:.3f} [{self.low:.3f}, {self.high:.3f}]"


def iqm(x: np.ndarray) -> float:
    """Interquartile mean: mean of the middle 50% of the samples.

    Robust to the one seed that diverged and the one that got lucky, which is why
    rliable recommends it over the mean for small-n RL comparisons.
    """

    x = np.sort(np.asarray(x, dtype=np.float64).ravel())
    n = x.size
    if n == 0:
        return float("nan")
    lo, hi = int(np.floor(n / 4)), int(np.ceil(3 * n / 4))
    return float(x[lo:hi].mean()) if hi > lo else float(x.mean())


def bootstrap_ci(
    x: np.ndarray,
    statistic=iqm,
    n_resamples: int = 10_000,
    confidence: float = 0.95,
    rng: np.random.Generator | None = None,
) -> Interval:
    """Percentile bootstrap CI for ``statistic`` over ``x`` (resampling seeds)."""

    rng = rng or np.random.default_rng(0)
    x = np.asarray(x, dtype=np.float64).ravel()
    if x.size == 0:
        return Interval(float("nan"), float("nan"), float("nan"))

    idx = rng.integers(0, x.size, size=(n_resamples, x.size))
    samples = np.array([statistic(x[i]) for i in idx])
    alpha = (1.0 - confidence) / 2.0
    return Interval(
        point=statistic(x),
        low=float(np.quantile(samples, alpha)),
        high=float(np.quantile(samples, 1.0 - alpha)),
    )


def iqm_ci(scores: np.ndarray, confidence: float = 0.95) -> Interval:
    """IQM with a stratified bootstrap CI, via rliable when it is available."""

    scores = np.asarray(scores, dtype=np.float64)
    try:
        from rliable import library as rly
        from rliable import metrics

        matrix = scores.reshape(1, -1) if scores.ndim == 1 else scores
        point, cis = rly.get_interval_estimates(
            {"algo": matrix},
            lambda x: np.array([metrics.aggregate_iqm(x)]),
            reps=10_000,
        )
        return Interval(
            point=float(point["algo"][0]),
            low=float(cis["algo"][0][0]),
            high=float(cis["algo"][1][0]),
        )
    except ImportError:
        return bootstrap_ci(scores, statistic=iqm, confidence=confidence)


def paired_permutation_test(
    a: np.ndarray, b: np.ndarray, n_resamples: int = 10_000, rng: np.random.Generator | None = None
) -> tuple[float, float]:
    """Two-sided paired permutation test on the mean difference ``a - b``.

    Under the null, the label within each pair is exchangeable, so the test
    statistic's null distribution is generated by randomly flipping the sign of
    each pair's difference -- never by shuffling across pairs, which would break
    the pairing.

    Returns
    -------
    (observed_difference, p_value)
    """

    rng = rng or np.random.default_rng(0)
    a = np.asarray(a, dtype=np.float64).ravel()
    b = np.asarray(b, dtype=np.float64).ravel()
    if a.size != b.size:
        raise ValueError(f"paired test needs equal lengths, got {a.size} and {b.size}")

    diff = a - b
    observed = float(diff.mean())

    signs = rng.choice([-1.0, 1.0], size=(n_resamples, diff.size))
    null = (signs * diff).mean(axis=1)
    p = float((np.abs(null) >= abs(observed)).mean())
    return observed, p


def win_rate_ci(
    outcomes: np.ndarray, n_resamples: int = 10_000, rng: np.random.Generator | None = None
) -> Interval:
    """Bootstrap CI for a win rate.

    ``outcomes`` scores each episode as 1.0 win / 0.5 draw / 0.0 loss, so draws
    are shared rather than silently counted as losses.
    """

    rng = rng or np.random.default_rng(0)
    outcomes = np.asarray(outcomes, dtype=np.float64).ravel()
    return bootstrap_ci(outcomes, statistic=np.mean, n_resamples=n_resamples, rng=rng)


def degradation(solo: float, competitive: float) -> float:
    """Relative change from a solo baseline to its head-to-head value.

    This is the RQ2 metric. Each agent is compared against *its own* Phase 4 solo
    evaluation, never against the other algorithm's, so a difference in solo skill
    cannot masquerade as a difference in robustness.
    """

    if solo == 0 or not np.isfinite(solo):
        return float("nan")
    return float((competitive - solo) / abs(solo))
